import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from '../frontend/node_modules/typescript/lib/typescript.js';
const source=readFileSync(new URL('../frontend/src/lib/doctorSlots.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const {doctorSlots,clinicStart}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const date='2026-10-29',now=new Date('2026-10-28T12:00:00Z');
const availability={horarios:[{diaSemana:4,desde:'09:15:00',hasta:'11:15:00'},{diaSemana:4,desde:'16:00:00',hasta:'19:00:00'}],ocupados:[{inicio:'2026-10-29T15:45:00Z',fin:'2026-10-29T16:15:00Z'}],bloqueados:[{inicio:'2026-10-29T23:00:00Z',fin:'2026-10-30T00:00:00Z'}]};
const slots=doctorSlots(date,30,availability,[],now);
assert.equal(slots[0].time,'09:15');
assert.equal(slots.find(s=>s.time==='09:15').available,true);
assert.equal(slots.find(s=>s.time==='09:30').available,false);
assert.equal(slots.find(s=>s.time==='10:15').available,true);
assert.equal(slots.find(s=>s.time==='16:45').available,false);
assert.equal(slots.find(s=>s.time==='18:00').available,true);
assert.equal(slots.at(-1).time,'18:30');
assert.equal(slots.some(s=>s.time==='12:00'),false);
assert.deepEqual(doctorSlots('2026-10-30',30,availability,[],now),[]);
assert.deepEqual(doctorSlots(date,30,{horarios:[],ocupados:[],bloqueados:[]},[],now),[]);
const patientBusy=[{inicio:'2026-10-29T15:15:00Z',fin:'2026-10-29T15:45:00Z'}];
assert.equal(doctorSlots(date,30,availability,patientBusy,now)[0].available,false);
assert.equal(doctorSlots(date,30,availability,[],new Date('2026-10-29T16:00:00Z'))[0].available,false);
const otherDoctor={horarios:[{diaSemana:4,desde:'14:00:00',hasta:'15:00:00'}],ocupados:[],bloqueados:[]};
assert.deepEqual(doctorSlots(date,30,otherDoctor,[],now).map(s=>s.time),['14:00','14:15','14:30']);
assert.deepEqual(doctorSlots(date,90,otherDoctor,[],now),[]);
assert.equal(clinicStart(date,'09:15').toISOString(),'2026-10-29T15:15:00.000Z');
console.log('OK: jornada del médico, cambio de médico, tarde, días libres, duración, cruces, bloqueos y zona horaria.');
